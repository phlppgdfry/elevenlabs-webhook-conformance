#!/usr/bin/env python3
"""Turn results/*.json into RESULTS.md: one row per vector, one column per SDK.

Every SDK reports the same error messages for the same failures, so outcomes are compared by
message. The consensus for a vector is the most common outcome among the released SDKs
(proposed PR branches do not vote). Cells that differ from it are marked.
"""

import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STANDARD = [
    ("Missing signature header", "missing header"),
    ("Webhook secret not configured", "missing secret"),
    ("No signature hash found", "no t/v0"),
    ("Timestamp outside the tolerance zone", "timestamp"),
    ("Signature hash does not match", "signature"),
]
PAYLOAD = re.compile(r"json|payload|parse|unexpected token|syntax|decode|object", re.I)


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def classify(result: dict, group: str) -> str:
    if result.get("ok"):
        return "ok"
    message = result.get("message") or ""
    for needle, label in STANDARD:
        if needle in message:
            return label
    if PAYLOAD.search(message) or PAYLOAD.search(result.get("error") or ""):
        return "invalid payload"
    return f"⚠ {result.get('error')}"  # an exception none of the documented outcomes cover


def main() -> None:
    sdks = json.loads((ROOT / "sdks.json").read_text())
    vectors = json.loads((ROOT / "vectors.json").read_text())["vectors"]
    columns = []
    for s in sdks:
        path = ROOT / "results" / f"{slug(s['name'])}.json"
        if path.exists():
            columns.append((s, json.loads(path.read_text())))

    lines = [
        "# Results",
        "",
        f"{len(vectors)} vectors × {len(columns)} SDK builds. Generated by `./run.sh`; do not edit by hand.",
        "",
        "Cells in **bold** differ from the consensus of the released SDKs. ⚠ marks an exception that is",
        "none of the documented outcomes (a crash rather than a rejection).",
        "",
    ]
    header = ["Vector"] + [s["name"] for s, _ in columns]
    lines += ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]

    divergences = Counter()
    notes = []
    for v in vectors:
        outcomes = [classify(r.get(v["id"], {"message": "missing result"}), v["group"]) for _, r in columns]
        released = [o for (s, _), o in zip(columns, outcomes) if "proposed" not in s]
        consensus = Counter(released).most_common(1)[0][0] if released else None
        cells = []
        for (s, _), o in zip(columns, outcomes):
            if o != consensus:
                cells.append(f"**{o}**")
                if "proposed" not in s:
                    divergences[s["name"]] += 1
                    notes.append((v, s["name"], o, consensus))
            else:
                cells.append(o)
        lines.append(f"| `{v['id']}` — {v['description']} | " + " | ".join(cells) + " |")

    lines += ["", "## Where the released SDKs disagree", ""]
    if notes:
        for v, name, got, want in notes:
            lines.append(f"- `{v['id']}`: **{name}** → {got} (others: {want})")
    else:
        lines.append("- Nowhere: every released SDK gives the same outcome for every vector.")
    broken = [s for s in sdks if (ROOT / "results" / f"{slug(s['name'])}.build-failed").exists()]
    if broken:
        lines += ["", "## SDK builds that failed", ""]
        for s in broken:
            lines.append(f"- **{s['name']}** @ `{s['ref'][:7]}` does not build, so it has no column. "
                         f"See `results/{slug(s['name'])}.build-failed`.")
    lines += ["", "## Pinned sources", ""]
    for s, _ in columns:
        link = f"https://github.com/{s['repo']}/blob/{s['ref']}/{s['file']}"
        extra = f" — proposed in {s['proposed']}" if "proposed" in s else ""
        if "note" in s:
            extra += f" — {s['note']}"
        lines.append(f"- {s['name']}: [`{s['file']}` @ `{s['ref'][:7]}`]({link}){extra}")
    (ROOT / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
